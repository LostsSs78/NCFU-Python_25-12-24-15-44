#!/usr/bin/env python3
# -*- coding: utf-8 -*-

if __name__ == "__main__":
    school = {
        "1а": 25,
        "1б": 24,
        "2б": 26,
        "6а": 30,
        "7в": 28
    }   

    # а) В одном из классов изменилось количество учащихся
    school["6а"] = 31
    print("После изменения количества учащихся в классе 6а:")
    print(school)

    # б) В школе появился новый класс
    school["3а"] = 27
    print("После добавления нового класса 3а:")
    print(school)

    # с) В школе был расформирован другой класс
    del school["1б"]
    print("После удаления класса 1б:")
    print(school)

    # Вычисление общего количества учащихся
    total_students = sum(school.values())
    print(f"Общее количество учащихся: {total_students}")